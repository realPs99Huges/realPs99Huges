import { Icon } from '../ui/Icon';
import { Modal } from '../ui/Modal';

export type NoticeKind = 'privacy' | 'demo';

const CONTENT: Record<NoticeKind, { kicker: string; title: string; intro: string; points: string[] }> = {
  privacy: {
    kicker: 'Privacy',
    title: 'Your sky stays with you.',
    intro: 'ASTRA is built so that your personal details never need to leave this page.',
    points: [
      'Birth date, time, places and your note are processed only in this browser tab.',
      'Nothing is saved — no cookies, no local storage, no account. Reloading the page clears everything.',
      'No data is sent to a server, an AI provider, a map or location service, or an analytics tool.',
      'Fonts are bundled with the site, so even typography makes no third-party requests.',
    ],
  },
  demo: {
    kicker: 'Demo & disclaimer',
    title: 'A prototype, told honestly.',
    intro: 'ASTRA is a design prototype that shows how a premium astrology experience could feel.',
    points: [
      'Readings are generated by a local, rule-based demo engine — not by an AI model. The engine is prepared to connect to one later.',
      'Astrology is symbolic. Birth data cannot reveal genetic ancestry, ethnicity or cultural origin, and ASTRA does not claim to.',
      'Nothing in a reading is a scientific diagnosis or a prediction of future events.',
      'The premium area is a simulation. No payment is requested, processed or stored, and no card details are ever asked for.',
    ],
  },
};

interface NoticeModalProps {
  notice: NoticeKind | null;
  onClose: () => void;
}

export function NoticeModal({ notice, onClose }: NoticeModalProps) {
  const content = notice ? CONTENT[notice] : null;
  return (
    <Modal open={!!notice} onClose={onClose} labelledBy="notice-title" describedBy="notice-intro">
      {content && (
        <>
          <p className="label label--gold">{content.kicker}</p>
          <h2 id="notice-title" className="modal__title">
            {content.title}
          </h2>
          <p id="notice-intro" className="modal__text">
            {content.intro}
          </p>
          <ul className="modal__list">
            {content.points.map((point) => (
              <li key={point}>
                <Icon name="check" size={16} />
                {point}
              </li>
            ))}
          </ul>
          <div className="modal__actions">
            <button type="button" className="btn btn--ghost" onClick={onClose}>
              Close
            </button>
          </div>
        </>
      )}
    </Modal>
  );
}
